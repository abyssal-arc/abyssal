/**
 * The dictionaries, by reference.
 *
 * Nothing in the app reads this. `test/i18n.test.js` does, to compare six key
 * sets that nothing else ever puts side by side — and the file already ships all
 * of it to every visitor who opens the devtools, so exporting costs no secrecy.
 */
export const DICT = dict;

const STORAGE_KEY = 'abyssal-lang';
let lang = localStorage.getItem(STORAGE_KEY) || 'en';
if (!dict[lang]) lang = 'en';

export function getLang() {
  return lang;
}

/** Translate a key, interpolating {placeholders} from params. */
export function t(key, params) {
  let s = (dict[lang] && dict[lang][key]) ?? dict.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** Apply translations to all elements carrying a data-i18n attribute. */
export function applyStaticI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll('#lang-menu [data-lang]').forEach((b) => {
    const on = b.dataset.lang === lang;
    b.classList.toggle('active', on);
    b.setAttribute('aria-selected', on ? 'true' : 'false');
  });
}

export function setLang(code) {
  if (!dict[code] || code === lang) return;
  lang = code;
  localStorage.setItem(STORAGE_KEY, code);
  document.documentElement.lang = code;
  applyStaticI18n();
  document.dispatchEvent(new CustomEvent('langchange'));
}

export function initI18n() {
  applyStaticI18n();
  const btn = document.getElementById('lang-btn');
  const menu = document.getElementById('lang-menu');
  if (!btn || !menu) return;
  const close = () => {
    menu.hidden = true;
    btn.setAttribute('aria-expanded', 'false');
  };
  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    menu.hidden = !menu.hidden;
    btn.setAttribute('aria-expanded', String(!menu.hidden));
  });
  menu.querySelectorAll('[data-lang]').forEach((b) => {
    b.addEventListener('click', () => {
      setLang(b.dataset.lang);
      close();
    });
  });
  document.addEventListener('click', (e) => {
    if (!menu.hidden && !menu.contains(e.target)) close();
  });
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') close();
  });
}
